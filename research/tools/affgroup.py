"""Affine automorphism group of a code C (as maps x -> sigma(x) + c), subgroups, and orbits on F_2^20.

An affine map is a pair (p, c): p is a tuple with p[i] = image coordinate of i, c an int.
apply(g, x) = perm(x, p) ^ c.  compose(g1, g2) = g1 after g2.
"""
import json, random

N = 20
SPACE = 1 << N


def tables(p):
    lo = [0] * 1024
    hi = [0] * 1024
    for x in range(1024):
        a = b = 0
        for i in range(10):
            if (x >> i) & 1:
                a |= 1 << p[i]
                b |= 1 << p[i + 10]
        lo[x] = a
        hi[x] = b
    return lo, hi


def perm_word(x, p):
    y = 0
    for i in range(N):
        if (x >> i) & 1:
            y |= 1 << p[i]
    return y


def compose(g1, g2):
    p1, c1 = g1
    p2, c2 = g2
    return (tuple(p1[p2[i]] for i in range(N)), perm_word(c2, p1) ^ c1)


def closure(gens, limit=10 ** 6):
    ident = (tuple(range(N)), 0)
    seen = {ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for h in frontier:
            for g in gens:
                k = compose(g, h)
                if k not in seen:
                    seen.add(k)
                    nxt.append(k)
                    if len(seen) > limit:
                        raise RuntimeError('group too large')
        frontier = nxt
    return seen


def orbits(gens):
    """orbit id per word of F_2^20 under the group generated by gens (union-find)."""
    parent = list(range(SPACE))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for p, c in gens:
        lo, hi = tables(p)
        for x in range(SPACE):
            y = lo[x & 1023] | hi[x >> 10]
            y ^= c
            a, b = find(x), find(y)
            if a != b:
                if a < b:
                    parent[b] = a
                else:
                    parent[a] = b
    oid = [0] * SPACE
    ids = {}
    for x in range(SPACE):
        rt = find(x)
        if rt not in ids:
            ids[rt] = len(ids)
        oid[x] = ids[rt]
    return oid, len(ids)


def record_affine_group(cons_path, perms):
    """Affine maps (sigma, c) with sigma(C) + c = C, for sigma in perms (coordinate automorphisms mod translation)."""
    f = json.load(open(cons_path))['integer_form']
    H, S = f['H_columns'], f['S']
    syn = [0] * SPACE
    for x in range(1, SPACE):
        low = x & -x
        syn[x] = syn[x ^ low] ^ H[low.bit_length() - 1]
    Sset = set(S)
    # a word with each syndrome
    rep = {}
    for x in range(SPACE):
        if syn[x] not in rep:
            rep[syn[x]] = x
    C = [x for x in range(SPACE) if syn[x] in Sset]
    out = []
    for p in perms:
        img = set(syn[perm_word(x, p)] for x in C)
        for d in set(s ^ S[0] for s in img):
            if set(s ^ d for s in img) == Sset:
                out.append((tuple(p), rep[d]))
                break
    L = [x for x in range(SPACE) if syn[x] == 0]
    return out, L, C
